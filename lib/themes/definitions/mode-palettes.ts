import type { ThemeColorTokens, ThemeId, ThemeModeTokens } from "../types";

export interface DualModePaletteSpec {
  light: ThemeModeTokens;
  dark: ThemeModeTokens;
}

function makePalette(
  c: Omit<ThemeColorTokens, "success" | "warning" | "error"> & {
    success?: string;
    warning?: string;
    error?: string;
  },
  surface: {
    shadow: string;
    shadowHover: string;
    backdrop?: string;
    surfaceOpacity?: string;
    gradient?: string;
  }
): ThemeModeTokens {
  return {
    colors: {
      success: "#16a34a",
      warning: "#d97706",
      error: "#dc2626",
      ...c,
    },
    shadow: surface.shadow,
    shadowHover: surface.shadowHover,
    backdrop: surface.backdrop ?? "none",
    surfaceOpacity: surface.surfaceOpacity ?? "1",
    gradient: surface.gradient ?? "none",
  };
}

